// Writes src/generated/autoconsent-script.ts: autoconsent's in-page script as a
// string, so the Worker can inject it into pages. Runs after npm install and
// before every wrangler build.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const dist = path.dirname(require.resolve('@duckduckgo/autoconsent'));
const source = readFileSync(path.join(dist, 'autoconsent.playwright.js'), 'utf8');
const { version } = JSON.parse(readFileSync(path.join(dist, '..', 'package.json'), 'utf8'));

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'generated');
mkdirSync(out, { recursive: true });
writeFileSync(
  path.join(out, 'autoconsent-script.ts'),
  '// Generated by scripts/consent-script.mjs. Do not edit.\n' +
    // A "/*!" comment is kept by the bundler, so the notice stays in the built Worker.
    `/*! @duckduckgo/autoconsent ${version}, Copyright DuckDuckGo, Inc. Subject to the terms of the\n` +
    ' * Mozilla Public License, v. 2.0: https://mozilla.org/MPL/2.0/. Source: https://github.com/duckduckgo/autoconsent */\n' +
    `export default ${JSON.stringify(source)};\n`,
);
